"""Durable dispatch envelopes and single-seat transport ownership.

Every mutation replaces one ledger under a kernel-held cross-process lock.
Transport release never admits a session result or calls the session engine.
"""
from contextlib import contextmanager
from copy import deepcopy
import json
from pathlib import Path
import re
import time
import uuid

from api_seats import atomic_json
from launcher import startup_lock


class QueueConflict(ValueError):
    pass


class QueueBusy(QueueConflict):
    pass


class QueueAccessError(PermissionError):
    pass


ACTIVE = {'dispatched', 'acknowledged', 'uncertain', 'cancelling'}
STATES = ACTIVE | {'queued', 'released', 'failed', 'cancelled'}


def _identifier(value, label):
    if not isinstance(value, str) or not re.fullmatch(r'[a-zA-Z0-9_.-]{1,128}', value):
        raise ValueError(f'{label} must be a nonempty identifier (at most 128 characters).')
    return value


def _seat(instance):
    if not isinstance(instance, dict) or not instance.get('name'):
        raise QueueAccessError('A registered seat identity is required.')
    return _identifier(instance.get('identity_id'), 'Seat identity')


def _routing(envelope):
    channel = envelope.get('channel', 'general')
    if not isinstance(channel, str) or not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,19}', channel):
        raise ValueError('Dispatch channel is invalid.')
    if 'job_id' in envelope and (type(envelope['job_id']) is not int or envelope['job_id'] < 0):
        raise ValueError('Dispatch job_id must be a nonnegative integer (zero means no job).')
    for key in ('prompt', 'text', 'sender', 'review_brief_id', 'run_id', 'turn_id', 'attempt_id', 'input_revision'):
        if key in envelope and not isinstance(envelope[key], str):
            raise ValueError(f'Dispatch {key} must be text.')


class QueueStore:
    def __init__(self, data_dir):
        self.root = Path(data_dir)
        self.path = self.root / 'queue' / 'ledger.json'

    @contextmanager
    def _transaction(self):
        with startup_lock(self.path.with_suffix('.json.lock'), time.monotonic() + 10):
            value = {'version': 1, 'records': []}
            if self.path.exists():
                value = json.loads(self.path.read_text(encoding='utf-8'))
            self._validate(value)
            yield value

    def _validate(self, value):
        if (not isinstance(value, dict) or value.get('version') != 1
                or not isinstance(value.get('records'), list)):
            raise ValueError('Dispatch ledger is malformed; it was preserved without replay.')
        ids, seats = set(), set()
        for record in value['records']:
            if (not isinstance(record, dict) or record.get('state') not in STATES
                    or not isinstance(record.get('envelope'), dict)
                    or not isinstance(record.get('events'), list)):
                raise ValueError('Dispatch receipt is malformed; queue is held.')
            envelope = record['envelope']
            _routing(envelope)
            dispatch_id = _identifier(envelope.get('dispatch_id'), 'Dispatch ID')
            identity = _identifier(envelope.get('target_identity_id'), 'Seat identity')
            if dispatch_id in ids or not isinstance(envelope.get('target_agent_name'), str):
                raise ValueError('Dispatch identity is malformed or duplicated.')
            ids.add(dispatch_id)
            if record['state'] in ACTIVE:
                _identifier(record.get('consumer_id'), 'Consumer ID')
                if identity in seats:
                    raise ValueError('Multiple dispatches own one seat; queue is held.')
                seats.add(identity)

    def _write(self, ledger):
        self._validate(ledger)
        atomic_json(self.path, ledger)

    @staticmethod
    def _event(record, state, error=''):
        record['state'] = state
        record['events'].append({'state': state, 'at': time.time(), 'error': error})

    def enqueue(self, instance, envelope):
        identity = _seat(instance)
        if not isinstance(envelope, dict):
            raise ValueError('A dispatch envelope object is required.')
        value = json.loads(json.dumps(envelope, allow_nan=False))
        _routing(value)
        value['dispatch_id'] = _identifier(value.get('dispatch_id', uuid.uuid4().hex), 'Dispatch ID')
        if value.get('target_identity_id', identity) != identity:
            raise QueueAccessError('Dispatch target does not match the registered seat.')
        value['target_identity_id'] = identity
        value['target_agent_name'] = instance['name']
        with self._transaction() as ledger:
            for record in ledger['records']:
                if record['envelope']['dispatch_id'] == value['dispatch_id']:
                    old = record['envelope']
                    # Wall-clock receipt timestamps are generated by the store,
                    # never part of an enqueue retry's semantic identity.
                    generated = {'created_at', 'target_agent_name'}
                    compare = {k: v for k, v in old.items() if k not in generated}
                    candidate = {k: v for k, v in value.items() if k not in generated}
                    if compare != candidate:
                        raise QueueConflict('Dispatch ID already exists with different fields or recipient.')
                    return deepcopy(record)
            value['created_at'] = time.time()
            record = {'envelope': value, 'state': 'queued', 'consumer_id': '', 'events': []}
            self._event(record, 'queued')
            ledger['records'].append(record)
            self._write(ledger)
            return deepcopy(record)

    def claim(self, instance, consumer_id, *, blocked_run_ids=None):
        identity = _seat(instance)
        _identifier(consumer_id, 'Consumer ID')
        blocked = set(blocked_run_ids or ())
        with self._transaction() as ledger:
            records = [r for r in ledger['records'] if r['envelope']['target_identity_id'] == identity]
            for record in records:
                if record['state'] in ACTIVE:
                    if record['envelope'].get('run_id') in blocked:
                        raise QueueBusy('Restart ownership is unverified; held work is retained.')
                    if record['consumer_id'] != consumer_id:
                        raise QueueBusy('Seat already owns a dispatch; pending work is retained.')
                    return deepcopy(record)
            for record in records:
                if record['state'] == 'queued':
                    if record['envelope'].get('run_id') in blocked:
                        continue
                    record['consumer_id'] = consumer_id
                    self._event(record, 'dispatched')
                    self._write(ledger)
                    return deepcopy(record)
            return None

    def _update(self, instance, dispatch_id, consumer_id, state, error='', http_status=None):
        identity = _seat(instance)
        _identifier(dispatch_id, 'Dispatch ID')
        _identifier(consumer_id, 'Consumer ID')
        with self._transaction() as ledger:
            record = next((r for r in ledger['records']
                           if r['envelope']['dispatch_id'] == dispatch_id), None)
            if (not record or record['envelope']['target_identity_id'] != identity
                    or record['consumer_id'] != consumer_id):
                raise QueueAccessError('Dispatch is not owned by this seat and consumer.')
            if record['state'] == state:
                return deepcopy(record)
            if state == 'acknowledged' and record['state'] == 'released':
                # A fast cooperative client may finish before inject() returns.
                # Its successful release already durably proves delivery.
                return deepcopy(record)
            if record['state'] not in ACTIVE:
                raise QueueConflict('Dispatch has no active ownership to update.')
            if record['state'] == 'cancelling':
                raise QueueConflict('Cancellation retains ownership until a local-ended receipt.')
            if state == 'acknowledged' and record['state'] != 'dispatched':
                raise QueueConflict('Uncertain ownership cannot be acknowledged automatically.')
            if state == 'released' and record['state'] == 'dispatched':
                self._event(record, 'acknowledged')
            self._event(record, state, error)
            if http_status is not None:
                record['events'][-1]['http_status'] = http_status
            self._write(ledger)
            return deepcopy(record)

    def acknowledge(self, instance, dispatch_id, consumer_id):
        return self._update(instance, dispatch_id, consumer_id, 'acknowledged')

    def release(self, instance, dispatch_id, consumer_id, *, failed=False, error='', http_status=None):
        # Deliberately no result content, engine callback or phase transition.
        if http_status is not None and (not failed or type(http_status) is not int or not 100 <= http_status <= 599):
            raise ValueError('Failure status must be an integer HTTP status code.')
        return self._update(instance, dispatch_id, consumer_id, 'failed' if failed else 'released', error, http_status)

    def uncertain(self, instance, dispatch_id, consumer_id):
        return self._update(instance, dispatch_id, consumer_id, 'uncertain',
                            'Delivery outcome is uncertain; ownership retained without replay.')

    def owned(self, instance, dispatch_id):
        """Resolve a cooperative release to the current owner without exposing it."""
        identity = _seat(instance)
        with self._transaction() as ledger:
            for record in ledger['records']:
                if (record['envelope']['dispatch_id'] == dispatch_id
                        and record['envelope']['target_identity_id'] == identity):
                    return deepcopy(record)
        raise QueueAccessError('Dispatch does not belong to this seat.')

    def cancel_run(self, run_id, stop_id):
        _identifier(run_id, 'Run ID')
        _identifier(stop_id, 'Stop ID')
        with self._transaction() as ledger:
            changed = False
            records = []
            for record in ledger['records']:
                if record['envelope'].get('run_id') != run_id:
                    continue
                if record['state'] == 'queued':
                    record['stop_id'] = stop_id
                    self._event(record, 'cancelled')
                    changed = True
                elif record['state'] in ACTIVE and record['state'] != 'cancelling':
                    record['stop_id'] = stop_id
                    record['cancellation'] = {'status': 'requested', 'at': time.time(),
                                              'remote_compute': 'unverified'}
                    self._event(record, 'cancelling')
                    changed = True
                records.append(deepcopy(record))
            if changed:
                self._write(ledger)
            return records

    def cancel_dispatch(self, dispatch_id, cancellation_id):
        """Fence one retried transport without touching its peers or successors."""
        _identifier(dispatch_id, 'Dispatch ID')
        _identifier(cancellation_id, 'Cancellation ID')
        with self._transaction() as ledger:
            record = next((r for r in ledger['records'] if r['envelope']['dispatch_id'] == dispatch_id), None)
            if record is None:
                return None
            if record['state'] == 'queued':
                record['cancellation_id'] = cancellation_id
                self._event(record, 'cancelled')
                self._write(ledger)
            elif record['state'] in ACTIVE and record['state'] != 'cancelling':
                record['cancellation_id'] = cancellation_id
                record['cancellation'] = {'status': 'requested', 'at': time.time(), 'remote_compute': 'unverified'}
                self._event(record, 'cancelling')
                self._write(ledger)
            return deepcopy(record)

    def for_identity(self, instance):
        identity = _seat(instance)
        with self._transaction() as ledger:
            return deepcopy([r for r in ledger['records'] if r['envelope']['target_identity_id'] == identity])

    def cancellation_receipt(self, instance, dispatch_id, consumer_id, status, *, remote_compute='unverified'):
        identity = _seat(instance)
        _identifier(dispatch_id, 'Dispatch ID')
        _identifier(consumer_id, 'Consumer ID')
        if status not in ('delivered', 'local_ended', 'unsupported', 'unresolved') or remote_compute != 'unverified':
            raise ValueError('Unsupported cancellation evidence.')
        with self._transaction() as ledger:
            record = next((r for r in ledger['records'] if r['envelope']['dispatch_id'] == dispatch_id), None)
            if (not record or record['envelope']['target_identity_id'] != identity
                    or record['consumer_id'] != consumer_id):
                raise QueueAccessError('Cancellation is not owned by this seat and consumer.')
            if record['state'] == 'cancelled' and record.get('cancellation', {}).get('status') == status:
                return deepcopy(record)
            if record['state'] != 'cancelling':
                raise QueueConflict('No cancellation is pending for this dispatch.')
            if record.get('cancellation', {}).get('status') == status:
                return deepcopy(record)
            record['cancellation'] = {'status': status, 'at': time.time(), 'remote_compute': remote_compute}
            record.setdefault('cancellation_receipts', []).append(deepcopy(record['cancellation']))
            if status == 'local_ended':
                self._event(record, 'cancelled')
            self._write(ledger)
            return deepcopy(record)

    def confirm_local_exit(self, dispatch_id, cancellation_id, *, evidence):
        """Internal operator-intent settlement, distinct from a worker receipt."""
        _identifier(dispatch_id, 'Dispatch ID')
        _identifier(cancellation_id, 'Cancellation ID')
        allowed = {'durable_receipt_and_observed_absent', 'all_bound_invocations_ended',
                   'protocol_one_no_invocations', 'bound_invocation_birth_and_observed_absent',
                   'observed_child_exit_and_ipc'}
        if (not isinstance(evidence, dict) or evidence.get('local_ended') is not True
                or not isinstance(evidence.get('verification_basis'), str)
                or evidence['verification_basis'] not in allowed):
            raise QueueConflict('Verified local exit evidence is required.')
        launch = _identifier(evidence.get('launch_attempt'), 'Launch attempt')
        if not re.fullmatch(r'[0-9a-f]{32}', launch):
            raise QueueConflict('The exact launch attempt is required.')
        with self._transaction() as ledger:
            record = next((r for r in ledger['records'] if r['envelope']['dispatch_id'] == dispatch_id), None)
            if not record or record.get('cancellation_id') != cancellation_id:
                raise QueueConflict('The exact persisted cancellation request is required.')
            previous = record.get('cancellation', {})
            if (record['state'] == 'cancelled' and previous.get('status') == 'local_ended'
                    and previous.get('source') == 'runtime_reconciliation'
                    and previous.get('launch_attempt') == launch
                    and previous.get('verification_basis') == evidence['verification_basis']):
                return deepcopy(record)
            if record['state'] != 'cancelling':
                raise QueueConflict('No cancellation is pending for this dispatch.')
            receipt = {'status': 'local_ended', 'at': time.time(), 'remote_compute': 'unverified',
                       'source': 'runtime_reconciliation', 'launch_attempt': launch,
                       'verification_basis': evidence['verification_basis']}
            record['cancellation'] = receipt
            record.setdefault('cancellation_receipts', []).append(deepcopy(receipt))
            self._event(record, 'cancelled')
            self._write(ledger)
            return deepcopy(record)

    def status(self):
        with self._transaction() as ledger:
            seats = {}
            for record in ledger['records']:
                envelope = record['envelope']
                identity = envelope['target_identity_id']
                seat = seats.setdefault(identity, {'name': envelope['target_agent_name'],
                    'queued': 0, 'failed': 0, 'active': None, 'contention': False})
                if record['state'] == 'queued':
                    seat['queued'] += 1
                if record['state'] == 'failed':
                    seat['failed'] += 1
                    seat['last_failure'] = {'dispatch_id': envelope['dispatch_id'],
                                            'category': record['events'][-1].get('error') or 'transport_failure'}
                if record['state'] in ACTIVE:
                    seat['active'] = {'dispatch_id': envelope['dispatch_id'],
                                      'state': record['state'], 'awaiting_release': True}
            for seat in seats.values():
                seat['contention'] = bool(seat['queued'] and seat['active'])
            return {'seats': seats,
                    'legacy_unmigrated_files': sorted(p.name for p in self.root.glob('*_queue.jsonl'))}
